//! The demo plugins in `tests/fixtures/` for the shells' tests (CLI, desktop, web e2e): a
//! small hand-written module per version, built from the WAT below. The committed `.wasm`
//! files must match; `RT_UPDATE_FIXTURES=1 cargo test -p rt-plugin --test fixtures` rewrites
//! them.
//!
//! The demo answers every hook: `prepare` sets `X-Demo-Plugin: <version>` and adds a note,
//! `response` adds a note, its request and response tabs render a small view with an
//! action, its importer `demo` turns any file into a one-request collection.

mod support;

use std::path::PathBuf;

use rt_core::services::{HookContext, RequestHooks};
use rt_plugin::host::PluginHost;
use serde_json::json;
use support::{Fake, block_on, request};

fn wat_string(s: &str) -> String {
    let mut out = String::new();
    for b in s.bytes() {
        match b {
            0x20..=0x7e if b != b'"' && b != b'\\' => out.push(b as char),
            _ => out.push_str(&format!("\\{b:02x}")),
        }
    }
    out
}

fn demo_wat(version: &str, permissions: serde_json::Value) -> String {
    demo_wat_with(version, permissions, None)
}

/// `welcome`: a first-start choice (wave 6), for the shells' tests of bundled plugins.
fn demo_wat_with(
    version: &str,
    permissions: serde_json::Value,
    welcome: Option<serde_json::Value>,
) -> String {
    let mut manifest = json!({
        "id": "demo",
        "name": "Demo plugin",
        "version": version,
        "api": 1,
        "description": "Shows what a plugin can do: a header, notes, two tabs and an importer.",
        "license": "Apache-2.0",
        "permissions": permissions,
        "contributes": {
            "prepare": true,
            "response": true,
            "tabs": [
                {"id": "demo-request", "title": "Demo", "place": "request"},
                {"id": "demo-response", "title": "Demo", "place": "response"}
            ],
            "importers": [{"id": "demo", "label": "Demo files (plugin)", "extensions": ["demo"]}]
        }
    });
    if let Some(welcome) = welcome {
        manifest["contributes"]["welcome"] = welcome;
    }
    let replies = [
        (
            "prepare",
            json!({"ok": {
                "patch": {"set_headers": [["X-Demo-Plugin", version]]},
                "notes": [{"level": "info", "text": "Demo plugin added X-Demo-Plugin"}]
            }}),
        ),
        (
            "response",
            json!({"ok": {"notes": [{"level": "info", "text": "Demo plugin saw the response"}]}}),
        ),
        (
            "render",
            json!({"ok": {
                "view": {"blocks": [
                    {"type": "heading", "text": "Demo plugin"},
                    {"type": "text", "text": "Rendered by a WebAssembly plugin."},
                    {"type": "key-value", "rows": [["API", "1"], ["Version", version]]},
                    {"type": "actions", "actions": [{"id": "hello", "label": "Say hello"}]}
                ]},
                "state": {"rendered": true}
            }}),
        ),
        (
            "action",
            json!({"ok": {"view": {"blocks": [
                {"type": "notice", "level": "info", "text": "Hello from the demo plugin"}
            ]}}}),
        ),
        ("detect", json!({"ok": {"matches": true}})),
        (
            "import",
            json!({"ok": {
                "collection_name": "Demo import",
                "files": [
                    ["opencollection.yml", "opencollection: 1.0.0\n\ninfo:\n  name: Demo import\n"],
                    ["hello.yml", "info:\n  name: Hello\n  type: http\n  seq: 1\n\nhttp:\n  method: GET\n  url: https://example.com/hello\n"]
                ],
                "report": {"format": "plugin", "requests": 1, "folders": 0, "environments": 0, "losses": []}
            }}),
        ),
    ];
    let mut data = String::new();
    let mut packed = std::collections::BTreeMap::new();
    let mut offset: u64 = 1024;
    for (name, reply) in &replies {
        let text = reply.to_string();
        data.push_str(&format!(
            "  (data (i32.const {offset}) \"{}\")\n",
            wat_string(&text)
        ));
        packed.insert(*name, (offset << 32) | text.len() as u64);
        offset += text.len() as u64 + 16;
    }
    let r = |name: &str| format!("(i64.const {})", packed[name]);
    format!(
        r#";; SPDX-License-Identifier: Apache-2.0
;; Copyright 2026 The RequestTailor Authors
;; Generated by crates/rt-plugin/tests/fixtures.rs (RT_UPDATE_FIXTURES=1); do not edit.
(module
  (memory (export "memory") 2)
  (global $bump (mut i32) (i32.const 65536))
{data}  (func (export "rt_alloc") (param $len i32) (result i32)
    (local $p i32)
    (local.set $p (global.get $bump))
    (global.set $bump (i32.add (global.get $bump) (local.get $len)))
    (block $ok
      (loop $grow
        (br_if $ok (i32.le_u (global.get $bump) (i32.mul (memory.size) (i32.const 65536))))
        (if (i32.eq (memory.grow (i32.const 1)) (i32.const -1)) (then (unreachable)))
        (br $grow)))
    (local.get $p))
  (func (export "rt_dealloc") (param i32 i32))
  ;; The call is {{"hook":"<name>",...}}: the hook's first letter is at offset 9.
  (func (export "rt_call") (param $ptr i32) (param $len i32) (result i64)
    (local $c i32)
    (local.set $c (i32.load8_u offset=9 (local.get $ptr)))
    (if (i32.eq (local.get $c) (i32.const 112)) (then (return {prepare})))
    (if (i32.eq (local.get $c) (i32.const 97)) (then (return {action})))
    (if (i32.eq (local.get $c) (i32.const 100)) (then (return {detect})))
    (if (i32.eq (local.get $c) (i32.const 105)) (then (return {import})))
    (if (i32.eq (i32.load8_u offset=11 (local.get $ptr)) (i32.const 115)) (then (return {response})))
    {render})
  (@custom "rt-plugin" "{manifest}")
)
"#,
        prepare = r("prepare"),
        action = r("action"),
        detect = r("detect"),
        import = r("import"),
        response = r("response"),
        render = r("render"),
        manifest = wat_string(&manifest.to_string()),
    )
}

fn fixtures() -> Vec<(&'static str, String)> {
    vec![
        ("demo.wasm", demo_wat("1.0.0", json!({"storage": true}))),
        (
            "demo-v2.wasm",
            demo_wat("2.0.0", json!({"storage": true, "network": ["{request}"]})),
        ),
        // A bundled plugin with a first-start choice (wave 6).
        (
            "demo-bundled.wasm",
            demo_wat_with(
                "1.0.0",
                json!({"storage": true}),
                Some(json!({"label": "Demo extras", "description": "The demo tabs and importer."})),
            ),
        ),
    ]
}

fn dir() -> PathBuf {
    PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("tests/fixtures")
}

#[test]
fn committed_fixtures_are_up_to_date() {
    let update = std::env::var_os("RT_UPDATE_FIXTURES").is_some();
    for (name, wat) in fixtures() {
        let wasm = wat::parse_str(&wat).expect("valid WAT");
        let path = dir().join(name);
        if update {
            std::fs::write(&path, &wasm).unwrap();
            std::fs::write(path.with_extension("wat"), &wat).unwrap();
        }
        let committed = std::fs::read(&path).unwrap_or_default();
        assert!(
            committed == wasm,
            "{name} is out of date: RT_UPDATE_FIXTURES=1 cargo test -p rt-plugin --test fixtures"
        );
    }
}

#[test]
fn the_demo_plugin_answers_every_hook() {
    let wasm = std::fs::read(dir().join("demo.wasm")).unwrap();
    let manifest = PluginHost::inspect(&wasm).unwrap();
    let fake = Fake::default();
    let mut host = PluginHost::new(Box::new(fake));
    host.load(&wasm, manifest.permissions.clone(), true)
        .unwrap();
    let ctx = HookContext {
        request_path: "a.yml".into(),
        environment: None,
        variables: Vec::new(),
    };
    let (sent, notes) = block_on(host.before_send(request("https://a.test/"), &[], &ctx)).unwrap();
    assert_eq!(
        sent.headers,
        vec![("X-Demo-Plugin".to_owned(), "1.0.0".to_owned())]
    );
    assert_eq!(notes[0].text, "Demo plugin added X-Demo-Plugin");
    let target = rt_plugin::api::TabTarget {
        request_path: "a.yml".into(),
        response_id: None,
    };
    let view = block_on(host.tab(
        "demo",
        "demo-request",
        None,
        target.clone(),
        Default::default(),
        None,
        None,
    ))
    .unwrap();
    assert_eq!(view.view.blocks.len(), 4);
    let view = block_on(host.tab(
        "demo",
        "demo-response",
        Some(("hello", vec![])),
        target,
        Default::default(),
        None,
        None,
    ))
    .unwrap();
    assert_eq!(view.view.blocks.len(), 1);
    assert!(block_on(host.detect("demo", "demo", vec![])).unwrap());
    let import = block_on(host.import("demo", "demo", vec![])).unwrap();
    assert_eq!(import.collection_name, "Demo import");
}
