//! The HTML of `rt docs`: one page, a table of contents, one section per folder (flattened,
//! with the folder path as heading) and one article per request.

use std::fmt::Write as _;

use rt_core::model::{
    ApiKeyPlacement, Auth, Body, Collection, Folder, Item, KeyValue, OAuth2Flow, Param, ParamKind,
    PartKind, Protocol, RawKind, RequestEntry,
};
use rt_core::prepare::{PrepareInput, scope};
use rt_core::vars::Scope;
use rt_format::CollectionDoc;
use rt_format::examples::{Example, ItemDocs, RequestExamples};

use super::mask::Masker;

/// The generated page.
#[derive(Debug, Clone)]
pub struct Rendered {
    pub html: String,
    /// Requests on the page.
    pub requests: usize,
    /// Values shown as `***` because they look like credentials.
    pub masked: usize,
}

/// Renders the documentation of `doc`. With `environment`, its non-secret variables are
/// filled in (an unknown name is an error).
pub fn render(doc: &CollectionDoc, environment: Option<&str>) -> Result<Rendered, String> {
    let model = doc.model();
    if let Some(env) = environment
        && model.environment(env).is_none()
    {
        return Err(format!("no environment {env:?} in the collection"));
    }
    let mut page = Page {
        doc,
        model,
        environment,
        examples: doc.examples(),
        masker: Masker::default(),
        out: String::new(),
        requests: 0,
    };
    page.document();
    Ok(Rendered {
        html: page.out,
        requests: page.requests,
        masked: page.masker.masked,
    })
}

/// HTML-escapes text for element content and attribute values.
pub(crate) fn esc(s: &str) -> String {
    let mut out = String::with_capacity(s.len());
    for c in s.chars() {
        match c {
            '&' => out.push_str("&amp;"),
            '<' => out.push_str("&lt;"),
            '>' => out.push_str("&gt;"),
            '"' => out.push_str("&quot;"),
            '\'' => out.push_str("&#39;"),
            c => out.push(c),
        }
    }
    out
}

/// An id for an item path: `r-users-get-user-yml`, `f-users`.
fn anchor(prefix: &str, path: &str) -> String {
    let mut id = String::from(prefix);
    id.push('-');
    for c in path.chars() {
        if c.is_ascii_alphanumeric() {
            id.push(c.to_ascii_lowercase());
        } else if !id.ends_with('-') {
            id.push('-');
        }
    }
    id.trim_end_matches('-').to_owned()
}

/// One folder section: the folders from the root down to it, and its own requests.
struct Section<'a> {
    chain: Vec<&'a Folder>,
    requests: Vec<&'a RequestEntry>,
}

fn sections<'a>(items: &'a [Item], chain: &mut Vec<&'a Folder>, out: &mut Vec<Section<'a>>) {
    let requests = items
        .iter()
        .filter_map(|i| match i {
            Item::Request(r) => Some(r),
            Item::Folder(_) => None,
        })
        .collect();
    out.push(Section {
        chain: chain.clone(),
        requests,
    });
    for item in items {
        if let Item::Folder(f) = item {
            chain.push(f);
            sections(&f.items, chain, out);
            chain.pop();
        }
    }
}

fn method_class(method: &str) -> &'static str {
    match method.to_ascii_uppercase().as_str() {
        "GET" => "get",
        "POST" => "post",
        "PUT" => "put",
        "PATCH" => "patch",
        "DELETE" => "delete",
        _ => "other",
    }
}

fn raw_label(kind: RawKind) -> &'static str {
    match kind {
        RawKind::Json => "JSON",
        RawKind::Text => "Text",
        RawKind::Xml => "XML",
        RawKind::Sparql => "SPARQL",
    }
}

struct Page<'a> {
    doc: &'a CollectionDoc,
    model: &'a Collection,
    environment: Option<&'a str>,
    examples: Vec<RequestExamples>,
    masker: Masker,
    out: String,
    requests: usize,
}

impl Page<'_> {
    fn w(&mut self, s: &str) {
        self.out.push_str(s);
    }

    fn document(&mut self) {
        let name = if self.model.name.is_empty() {
            "Collection".to_owned()
        } else {
            self.model.name.clone()
        };
        let model = self.model;
        let mut all = Vec::new();
        sections(&model.items, &mut Vec::new(), &mut all);
        let title = esc(&name);
        let _ = write!(
            self.out,
            "<!doctype html>
<!-- Generated by rt docs {version} (RequestTailor) from the collection files. -->
<html lang=\"en\">
<head>
<meta charset=\"utf-8\">
<meta name=\"viewport\" content=\"width=device-width, initial-scale=1\">
<meta http-equiv=\"Content-Security-Policy\" content=\"default-src 'none'; style-src 'self'; base-uri 'none'; form-action 'none'\">
<meta name=\"referrer\" content=\"no-referrer\">
<meta name=\"generator\" content=\"rt docs {version}\">
<title>{title}: API documentation</title>
<link rel=\"stylesheet\" href=\"style.css\">
</head>
<body>
<a class=\"skip\" href=\"#main\">Skip to content</a>
<div class=\"layout\">
",
            version = env!("CARGO_PKG_VERSION"),
        );
        self.toc(&all);
        self.w("<main id=\"main\">\n");
        let _ = writeln!(self.out, "<h1>{title}</h1>");
        let env = match self.environment {
            Some(e) => format!("Environment <strong>{}</strong>", esc(e)),
            None => "No environment: values are shown as written in the files".to_owned(),
        };
        let _ = writeln!(self.out, "<p class=\"meta\">{env}</p>");
        let docs = self.doc.item_docs("");
        self.item_docs(&docs);
        self.collection_defaults();
        self.environments();
        for section in &all {
            self.section(section);
        }
        self.w(
            "</main>
</div>
<footer class=\"footer\">
<p>Generated by <code>rt docs</code> from the collection files. Secret values are never part of this page.</p>
</footer>
</body>
</html>
",
        );
    }

    fn toc(&mut self, all: &[Section<'_>]) {
        self.w("<nav class=\"toc\" aria-label=\"Requests\">\n<ul>\n");
        for s in all {
            if s.requests.is_empty() && s.chain.is_empty() {
                continue;
            }
            let folder = s.chain.last();
            if let Some(f) = folder {
                let label: Vec<&str> = s.chain.iter().map(|f| f.name.as_str()).collect();
                let _ = writeln!(
                    self.out,
                    "<li class=\"toc-folder\"><a href=\"#{}\">{}</a></li>",
                    anchor("f", &f.path),
                    esc(&label.join(" / "))
                );
            }
            for r in &s.requests {
                let _ = writeln!(
                    self.out,
                    "<li><a href=\"#{}\"><span class=\"method {}\">{}</span> {}</a></li>",
                    anchor("r", &r.path),
                    method_class(&r.spec.method),
                    esc(&r.spec.method),
                    esc(&r.spec.name)
                );
            }
        }
        self.w("</ul>\n</nav>\n");
    }

    fn item_docs(&mut self, docs: &ItemDocs) {
        if let Some(d) = &docs.description {
            let _ = writeln!(self.out, "<p class=\"description\">{}</p>", esc(d));
        }
        if let Some(d) = &docs.docs {
            let _ = writeln!(self.out, "<div class=\"docs-text\">{}</div>", esc(d));
        }
    }

    fn collection_defaults(&mut self) {
        let model = self.model;
        let defaults = &model.defaults;
        if defaults.headers.is_empty() && matches!(defaults.auth, Auth::None | Auth::Inherit) {
            return;
        }
        self.w("<section class=\"defaults\" aria-labelledby=\"defaults\">\n<h2 id=\"defaults\">For every request</h2>\n");
        if !matches!(defaults.auth, Auth::None | Auth::Inherit) {
            let auth = self.auth_text(&defaults.auth);
            let _ = writeln!(self.out, "<p><strong>Auth:</strong> {auth}</p>");
        }
        self.key_values("Headers", &defaults.headers, &Scope::default());
        self.w("</section>\n");
    }

    fn environments(&mut self) {
        let model = self.model;
        let envs = &model.environments;
        if envs.is_empty() {
            return;
        }
        self.w("<section aria-labelledby=\"environments\">\n<h2 id=\"environments\">Environments</h2>\n");
        let names: Vec<String> = envs
            .iter()
            .map(|e| format!("<code>{}</code>", esc(&e.name)))
            .collect();
        let _ = writeln!(self.out, "<p>{}</p>", names.join(", "));
        if let Some(env) = self.environment.and_then(|n| model.environment(n)) {
            let vars = &env.variables;
            self.w("<table>\n<thead><tr><th scope=\"col\">Variable</th><th scope=\"col\">Value</th></tr></thead>\n<tbody>\n");
            for v in vars.iter().filter(|v| v.enabled) {
                let value = match (&v.value, v.secret) {
                    (_, true) | (None, _) => format!(
                        "<code>{}</code> <span class=\"tag\">secret</span>",
                        esc(&format!("{{{{{}}}}}", v.name))
                    ),
                    (Some(value), false) => {
                        format!("<code>{}</code>", esc(&self.masker.named(&v.name, value)))
                    }
                };
                let _ = writeln!(
                    self.out,
                    "<tr><td><code>{}</code></td><td>{value}</td></tr>",
                    esc(&v.name)
                );
            }
            self.w("</tbody>\n</table>\n");
        }
        self.w("</section>\n");
    }

    fn section(&mut self, s: &Section<'_>) {
        if s.chain.is_empty() && s.requests.is_empty() {
            return;
        }
        match s.chain.last() {
            Some(f) => {
                let label: Vec<&str> = s.chain.iter().map(|f| f.name.as_str()).collect();
                let id = anchor("f", &f.path);
                let _ = writeln!(
                    self.out,
                    "<section class=\"folder\" aria-labelledby=\"{id}\">\n<h2 id=\"{id}\">{}</h2>",
                    esc(&label.join(" / "))
                );
                let docs = self.doc.item_docs(&f.path);
                self.item_docs(&docs);
            }
            None => self.w(
                "<section class=\"folder\" aria-labelledby=\"requests\">\n<h2 id=\"requests\">Requests</h2>\n",
            ),
        }
        for r in &s.requests {
            self.request(r);
        }
        self.w("</section>\n");
    }

    fn scope_for(&self, path: &str) -> Scope {
        let Some(context) = self.model.request(path) else {
            return Scope::default();
        };
        let input = PrepareInput {
            environment: self.environment,
            ..PrepareInput::default()
        };
        let mut scope = scope(&context, &input).unwrap_or_default();
        // Secret values are never in the files; drop the layers' secret entries anyway.
        for layer in &mut scope.layers {
            layer.vars.retain(|(_, _, secret)| !secret);
        }
        scope
    }

    fn request(&mut self, r: &RequestEntry) {
        self.requests += 1;
        let scope = self.scope_for(&r.path);
        let spec = &r.spec;
        let id = anchor("r", &r.path);
        let label = match &spec.protocol {
            Protocol::Http => spec.method.clone(),
            Protocol::Grpc(_) => "gRPC".to_owned(),
            Protocol::WebSocket(_) => "WS".to_owned(),
        };
        let _ = writeln!(
            self.out,
            "<article class=\"request\" aria-labelledby=\"{id}\">\n<h3 id=\"{id}\"><span class=\"method {}\">{}</span> {}</h3>",
            method_class(&label),
            esc(&label),
            esc(&spec.name)
        );
        let url = self.value("url", &interpolate(&scope, &spec.url));
        let _ = writeln!(self.out, "<p class=\"url\"><code>{}</code></p>", esc(&url));
        let _ = writeln!(
            self.out,
            "<p class=\"file\">File <code>{}</code></p>",
            esc(&r.path)
        );
        let docs = self.doc.item_docs(&r.path);
        self.item_docs(&docs);
        if let Protocol::Grpc(g) = &spec.protocol {
            let _ = writeln!(
                self.out,
                "<p><strong>Method:</strong> <code>{}</code></p>",
                esc(&g.method)
            );
        }
        let auth = self.effective_auth(r);
        let _ = writeln!(self.out, "<p><strong>Auth:</strong> {auth}</p>");
        self.params("Parameters", &spec.params, &scope);
        self.key_values("Headers", &spec.headers, &scope);
        let inherited = self.inherited_headers(r);
        if !inherited.is_empty() {
            self.key_values(
                "Headers from the collection and folders",
                &inherited,
                &scope,
            );
        }
        self.body("Body", &spec.body, &scope);
        let examples = self
            .examples
            .iter()
            .find(|e| e.path == r.path)
            .map(|e| e.examples.clone())
            .unwrap_or_default();
        if !examples.is_empty() {
            self.w("<h4>Examples</h4>\n");
            for e in &examples {
                self.example(e, &scope);
            }
        }
        self.w("</article>\n");
    }

    /// A single value (URL, ...): the credential check for a field `key`.
    fn value(&mut self, key: &str, value: &str) -> String {
        self.masker.field(key, value)
    }

    fn inherited_headers(&self, r: &RequestEntry) -> Vec<KeyValue> {
        let Some(context) = self.model.request(&r.path) else {
            return Vec::new();
        };
        let mut out: Vec<KeyValue> = self.model.defaults.headers.clone();
        for f in &context.folders {
            out.extend(f.defaults.headers.iter().cloned());
        }
        out
    }

    /// The auth that applies, and where it comes from.
    fn effective_auth(&mut self, r: &RequestEntry) -> String {
        if !matches!(r.spec.auth, Auth::Inherit) {
            return self.auth_text(&r.spec.auth);
        }
        let model = self.model;
        let Some(context) = model.request(&r.path) else {
            return "inherited".to_owned();
        };
        for f in context.folders.iter().rev() {
            if !matches!(f.defaults.auth, Auth::Inherit) {
                let text = self.auth_text(&f.defaults.auth);
                return format!("{text}, from the folder {}", esc(&f.name));
            }
        }
        let text = self.auth_text(&model.defaults.auth);
        format!("{text}, from the collection")
    }

    /// The auth type and the variables it uses; never a value.
    fn auth_text(&mut self, auth: &Auth) -> String {
        let mut t =
            |key: &str, v: &str| format!("<code>{}</code>", esc(&self.masker.field(key, v)));
        match auth {
            Auth::Inherit | Auth::None => "none".to_owned(),
            Auth::Basic { username, password } => format!(
                "Basic, user {}, password {}",
                t("username", username),
                t("password", password)
            ),
            Auth::Bearer { token } => format!("Bearer token {}", t("token", token)),
            Auth::ApiKey {
                key,
                value,
                placement,
            } => format!(
                "API key <code>{}</code> in the {}, value {}",
                esc(key),
                match placement {
                    ApiKeyPlacement::Header => "header",
                    ApiKeyPlacement::Query => "query",
                },
                t("apiKey", value)
            ),
            Auth::OAuth2(o) => {
                let flow = match &o.flow {
                    OAuth2Flow::ClientCredentials => "client credentials",
                    OAuth2Flow::Password { .. } => "password",
                    OAuth2Flow::AuthorizationCode { .. } => "authorization code",
                    OAuth2Flow::Implicit { .. } => "implicit",
                    OAuth2Flow::DeviceCode { .. } => "device code",
                    OAuth2Flow::Saml2Bearer { .. } => "SAML 2.0 bearer",
                };
                let url = if o.access_token_url.is_empty() {
                    String::new()
                } else {
                    format!(", token URL {}", t("url", &o.access_token_url))
                };
                format!("OAuth 2.0, {flow}{url}")
            }
            Auth::AwsSigV4(a) => format!(
                "AWS Signature Version 4, service {}, region {}",
                t("service", &a.service),
                t("region", &a.region)
            ),
            Auth::Unsupported { kind } => format!("{} (not supported)", esc(kind)),
        }
    }

    fn key_values(&mut self, title: &str, list: &[KeyValue], scope: &Scope) {
        if list.is_empty() {
            return;
        }
        let _ = writeln!(
            self.out,
            "<h4>{}</h4>\n<table>\n<thead><tr><th scope=\"col\">Name</th><th scope=\"col\">Value</th></tr></thead>\n<tbody>",
            esc(title)
        );
        for kv in list {
            let value = self.masker.named(&kv.name, &interpolate(scope, &kv.value));
            let off = if kv.enabled {
                ""
            } else {
                " <span class=\"tag\">disabled</span>"
            };
            let _ = writeln!(
                self.out,
                "<tr><td><code>{}</code>{off}</td><td><code>{}</code></td></tr>",
                esc(&kv.name),
                esc(&value)
            );
        }
        self.w("</tbody>\n</table>\n");
    }

    fn params(&mut self, title: &str, list: &[Param], scope: &Scope) {
        if list.is_empty() {
            return;
        }
        let _ = writeln!(
            self.out,
            "<h4>{}</h4>\n<table>\n<thead><tr><th scope=\"col\">Name</th><th scope=\"col\">In</th><th scope=\"col\">Value</th></tr></thead>\n<tbody>",
            esc(title)
        );
        for p in list {
            let value = self.masker.named(&p.name, &interpolate(scope, &p.value));
            let off = if p.enabled {
                ""
            } else {
                " <span class=\"tag\">disabled</span>"
            };
            let kind = match p.kind {
                ParamKind::Query => "query",
                ParamKind::Path => "path",
            };
            let _ = writeln!(
                self.out,
                "<tr><td><code>{}</code>{off}</td><td>{kind}</td><td><code>{}</code></td></tr>",
                esc(&p.name),
                esc(&value)
            );
        }
        self.w("</tbody>\n</table>\n");
    }

    fn pre(&mut self, text: &str) {
        let text = self.masker.text(text);
        let _ = writeln!(self.out, "<pre><code>{}</code></pre>", esc(&text));
    }

    fn body(&mut self, title: &str, body: &Body, scope: &Scope) {
        match body {
            Body::None => {}
            Body::Raw { kind, data } => {
                let _ = writeln!(
                    self.out,
                    "<h4>{} <span class=\"tag\">{}</span></h4>",
                    esc(title),
                    raw_label(*kind)
                );
                self.pre(&interpolate(scope, data));
            }
            Body::GraphQl { query, variables } => {
                let _ = writeln!(
                    self.out,
                    "<h4>{} <span class=\"tag\">GraphQL</span></h4>",
                    esc(title)
                );
                self.pre(&interpolate(scope, query));
                if !variables.trim().is_empty() {
                    self.w("<p>Variables</p>\n");
                    self.pre(&interpolate(scope, variables));
                }
            }
            Body::FormUrlEncoded { fields } => {
                self.key_values(&format!("{title} (form, URL-encoded)"), fields, scope)
            }
            Body::Multipart { parts } => {
                let _ = writeln!(
                    self.out,
                    "<h4>{} <span class=\"tag\">multipart</span></h4>\n<table>\n<thead><tr><th scope=\"col\">Name</th><th scope=\"col\">Value</th></tr></thead>\n<tbody>",
                    esc(title)
                );
                for p in parts {
                    let value = match p.kind {
                        PartKind::File => format!("file {}", p.values.join(", ")),
                        PartKind::Text => self
                            .masker
                            .named(&p.name, &interpolate(scope, &p.values.join(", "))),
                    };
                    let _ = writeln!(
                        self.out,
                        "<tr><td><code>{}</code></td><td><code>{}</code></td></tr>",
                        esc(&p.name),
                        esc(&value)
                    );
                }
                self.w("</tbody>\n</table>\n");
            }
            Body::File { path, content_type } => {
                let ct = content_type
                    .as_deref()
                    .map(|c| format!(" ({})", esc(c)))
                    .unwrap_or_default();
                let _ = writeln!(
                    self.out,
                    "<h4>{}</h4>\n<p>File <code>{}</code>{ct}</p>",
                    esc(title),
                    esc(path)
                );
            }
        }
    }

    fn example(&mut self, e: &Example, scope: &Scope) {
        let status = match &e.response.status_text {
            Some(t) if !t.is_empty() => format!("{} {}", e.response.status, t),
            _ => e.response.status.to_string(),
        };
        let name = if e.name.is_empty() {
            "Example"
        } else {
            &e.name
        };
        let _ = writeln!(
            self.out,
            "<details class=\"example\">\n<summary>{} <span class=\"status s{}\">{}</span></summary>",
            esc(name),
            e.response.status / 100,
            esc(&status)
        );
        if let Some(d) = &e.description {
            let _ = writeln!(self.out, "<p class=\"description\">{}</p>", esc(d));
        }
        let req = &e.request;
        if req.url.is_some() || req.method.is_some() {
            let url = req
                .url
                .as_deref()
                .map(|u| self.value("url", &interpolate(scope, u)))
                .unwrap_or_default();
            let _ = writeln!(
                self.out,
                "<p class=\"url\"><code>{} {}</code></p>",
                esc(req.method.as_deref().unwrap_or("")),
                esc(&url)
            );
        }
        self.params("Request parameters", &req.params, scope);
        self.key_values("Request headers", &req.headers, scope);
        self.body("Request body", &req.body, scope);
        let headers: Vec<KeyValue> = e
            .response
            .headers
            .iter()
            .map(|(n, v)| KeyValue::new(n.clone(), v.clone()))
            .collect();
        self.key_values("Response headers", &headers, &Scope::default());
        if let Some(b) = &e.response.body {
            let _ = writeln!(
                self.out,
                "<h4>Response body <span class=\"tag\">{}</span></h4>",
                esc(&b.kind)
            );
            self.pre(&b.data);
        }
        self.w("</details>\n");
    }
}

fn interpolate(scope: &Scope, text: &str) -> String {
    if text.contains("{{") {
        scope.interpolate(text).value
    } else {
        text.to_owned()
    }
}
