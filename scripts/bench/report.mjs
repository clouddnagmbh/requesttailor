// Tables from a benchmark result (bench/results/<date>-<os>.json): Markdown next to the
// JSON, and the results table of the website's benchmark page (website/benchmark/), with the
// budgets of perf/budgets.toml as the reference row.
//
// Usage: node scripts/bench/report.mjs [<result.json>] [--website <page.html>] [--markdown <file>]
//   Without a file: the newest result in bench/results/. Without options: prints Markdown.

import { existsSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

import { parseBudgets } from "../check-perf-budgets.mjs";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..", "..");
export const RESULTS_DIR = join(ROOT, "bench", "results");
export const START = "<!-- bench:results:start (generated by scripts/bench/report.mjs) -->";
export const END = "<!-- bench:results:end -->";

/** The columns: metric key, heading, unit, budget metric (or null). */
export const COLUMNS = [
  { key: "first_window", title: "First window", unit: "ms", budget: null },
  { key: "cold_start", title: "First interactive frame", unit: "ms", budget: "cold_start" },
  { key: "idle_memory", title: "Idle memory", unit: "MB", budget: "idle_memory" },
  { key: "large_response_frame", title: "100 MB response, p95 frame", unit: "ms", budget: "large_response_frame" },
  { key: "send_keystrokes", title: "Keystrokes to a sent request", unit: "", budget: "send_keystrokes" },
];

/** Budgets (metric → max) from perf/budgets.toml. */
export function budgetMaxima(text) {
  return Object.fromEntries(Object.entries(parseBudgets(text)).map(([k, m]) => [k, m.max]));
}

/** The newest `<date>-<os>.json` in `dir` (names sort by date). */
export function latestResult(dir = RESULTS_DIR) {
  const files = existsSync(dir)
    ? readdirSync(dir)
        .filter((f) => /^\d{4}-\d{2}-\d{2}-[a-z]+\.json$/.test(f))
        .sort()
    : [];
  return files.length === 0 ? null : join(dir, files[files.length - 1]);
}

/** The block the page shows before the first result is committed. */
export const NO_RESULT = `${START}\n<p>No measurement yet.</p>\n${END}`;

const fmt = (v, unit) => (unit ? `${v} ${unit}` : String(v));

/** One cell: the value, or why there is none. */
export function cell(app, column) {
  if (!app.installed) return "not installed";
  if (app.error) return "failed";
  const v = app.results?.[column.key];
  if (typeof v === "number") return fmt(v, column.unit);
  return app.notApplicable?.[column.key] ? "n/a" : "not measured";
}

function versionText(app) {
  if (!app.installed) return "";
  return [app.version ?? "?", app.commit ? `(${app.commit})` : ""].filter(Boolean).join(" ");
}

/** The rows as plain values: budget row first, then one per app. */
export function rows(result, budgets) {
  const budgetRow = {
    name: "Budget (RequestTailor)",
    version: "perf/budgets.toml",
    cells: COLUMNS.map((c) => (c.budget ? `≤ ${fmt(budgets[c.budget], c.unit)}` : "")),
  };
  return [
    budgetRow,
    ...result.apps.map((app) => ({ name: app.name, version: versionText(app), cells: COLUMNS.map((c) => cell(app, c)) })),
  ];
}

function machineText(result) {
  const m = result.machine;
  return `${m.model ?? m.arch}, ${m.cpu}, ${m.cpus} CPUs, ${m.memoryGB} GB, ${m.osName} ${m.osVersion}`;
}

export function markdown(result, budgets) {
  const head = `| App | Version | ${COLUMNS.map((c) => c.title).join(" | ")} |`;
  const sep = `| --- | --- | ${COLUMNS.map(() => "---:").join(" | ")} |`;
  const body = rows(result, budgets).map((r) => `| ${r.name} | ${r.version} | ${r.cells.join(" | ")} |`);
  const notes = result.apps.flatMap((a) => (a.notes ?? []).map((n) => `- ${a.name}: ${n}`));
  const errors = result.apps.filter((a) => a.error).map((a) => `- ${a.name}: ${a.error}`);
  return [
    `# Benchmark ${result.date.slice(0, 10)} (${result.machine.osName})`,
    "",
    `Machine: ${machineText(result)}. Node ${result.node}. Load average at start: ${result.loadAverage.join(", ")}.`,
    `Starts per app: ${result.method.runs} (the first is discarded), memory in the last ${result.method.memoryRuns}; values are medians.`,
    "",
    head,
    sep,
    ...body,
    "",
    ...(notes.length > 0 ? ["Notes:", "", ...notes, ""] : []),
    ...(errors.length > 0 ? ["Failed:", "", ...errors, ""] : []),
    "Method and definitions: [bench/README.md](../README.md). Generated by `scripts/bench/report.mjs`.",
    "",
  ].join("\n");
}

const esc = (s) => String(s).replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;").replace(/"/g, "&quot;");

/** The website's results block (between START and END): a table and the machine line. */
export function websiteBlock(result, budgets) {
  const [budgetRow, ...appRows] = rows(result, budgets);
  const th = COLUMNS.map((c) => `<th scope="col">${esc(c.title)}</th>`).join("");
  const budgetCells = COLUMNS.map((c) =>
    c.budget ? `<td>at most <span data-budget="${c.budget}">${budgets[c.budget]}</span>${c.unit ? ` ${c.unit}` : ""}</td>` : "<td></td>",
  ).join("");
  const lines = [
    START,
    `<p>Measured on ${esc(result.date.slice(0, 10))}: ${esc(machineText(result))}. Medians of ${result.method.runs - 1} starts per app after one warm-up start.</p>`,
    "<table>",
    `<thead><tr><th scope="col">App</th><th scope="col">Version</th>${th}</tr></thead>`,
    "<tbody>",
    `<tr><th scope="row">${esc(budgetRow.name)}</th><td></td>${budgetCells}</tr>`,
    ...appRows.map((r) => `<tr><th scope="row">${esc(r.name)}</th><td>${esc(r.version)}</td>${r.cells.map((c) => `<td>${esc(c)}</td>`).join("")}</tr>`),
    "</tbody>",
    "</table>",
  ];
  const notes = result.apps.flatMap((a) => (a.notes ?? []).map((n) => `<li>${esc(a.name)}: ${esc(n)}</li>`));
  if (notes.length > 0) lines.push("<ul>", ...notes, "</ul>");
  lines.push(END);
  return lines.join("\n");
}

/** `page` with the block between START and END replaced. */
export function replaceBlock(page, block) {
  const a = page.indexOf(START);
  const b = page.indexOf(END);
  if (a < 0 || b < a) throw new Error(`the page has no ${START} ... ${END} block`);
  return page.slice(0, a) + block + page.slice(b + END.length);
}

function main(argv) {
  let file = null;
  let website = null;
  let md = null;
  for (let i = 0; i < argv.length; i++) {
    if (argv[i] === "--website") website = resolve(argv[++i]);
    else if (argv[i] === "--markdown") md = resolve(argv[++i]);
    else if (!argv[i].startsWith("--") && file === null) file = resolve(argv[i]);
    else throw new Error(`unknown option ${argv[i]}`);
  }
  file ??= latestResult();
  if (!file) throw new Error(`no results in ${RESULTS_DIR}; run node scripts/bench/run.mjs`);
  const result = JSON.parse(readFileSync(file, "utf8"));
  const budgets = budgetMaxima(readFileSync(join(ROOT, "perf", "budgets.toml"), "utf8"));
  if (md) writeFileSync(md, markdown(result, budgets));
  if (website) writeFileSync(website, replaceBlock(readFileSync(website, "utf8"), websiteBlock(result, budgets)));
  if (!md && !website) process.stdout.write(markdown(result, budgets));
}

if (process.argv[1] && import.meta.url === pathToFileURL(resolve(process.argv[1])).href) {
  try {
    main(process.argv.slice(2));
  } catch (e) {
    console.error(e.message);
    process.exit(1);
  }
}
